"""Release isolation and first-run behavior; no connected services are called."""
import importlib.util
import json
from pathlib import Path
import shutil
import sys
import zipfile

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
import build_release

spec = importlib.util.spec_from_file_location('job_seeker_launcher', ROOT / 'launcher.py')
launcher = importlib.util.module_from_spec(spec)
spec.loader.exec_module(launcher)


@pytest.fixture
def clean_source(tmp_path):
    source = tmp_path / 'source folder with spaces'
    for relative in build_release.RELEASE_FILES:
        if relative == 'START HERE.html':
            continue  # Generated by the release builder.
        target = source / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / relative, target)
    return source


def test_release_excludes_runtime_secrets_and_preserves_launcher_mode(clean_source, tmp_path):
    for relative in ['workspace/data/profile.json', '.env', 'output/Resume.pdf', '.venv/credential.txt']:
        target = clean_source / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text('PRIVATE SENTINEL THAT MUST NEVER SHIP')
    archive, manifest = build_release.build(clean_source, tmp_path / 'release')
    with zipfile.ZipFile(archive) as z:
        assert not z.testzip()
        assert len(z.namelist()) == len(build_release.RELEASE_FILES) + 1
        assert all(b'PRIVATE SENTINEL' not in z.read(name) for name in z.namelist())
        command = next(i for i in z.infolist() if i.filename.endswith('/Start Job Seeker.command'))
        assert command.external_attr >> 16 & 0o777 == 0o755
        assert json.loads(z.read(command.filename.split('/')[0] + '/RELEASE-MANIFEST.json')) == manifest
    assert archive.with_suffix('.zip.sha256').is_file()


@pytest.mark.parametrize('relative', ['README.md', 'docs/USER-GUIDE.md', 'START HERE.html'])
def test_release_refuses_symlinked_source(clean_source, tmp_path, relative):
    target = clean_source / relative
    target.unlink(missing_ok=True)
    outside = tmp_path / 'outside.txt'
    outside.write_text('do not read outside release')
    target.symlink_to(outside)
    with pytest.raises(ValueError, match='Symlink refused'):
        build_release.build(clean_source, tmp_path / 'release')
    assert outside.read_text() == 'do not read outside release'
    assert not list((tmp_path / 'release').glob('*.zip'))


def test_release_refuses_embedded_credentials_before_writing_archive(clean_source, tmp_path):
    with (clean_source / 'README.md').open('a') as f:
        f.write('\n' + 'sk-proj-' + 'a' * 40)
    with pytest.raises(ValueError, match='Privacy scan failed'):
        build_release.build(clean_source, tmp_path / 'release')
    assert not list((tmp_path / 'release').glob('*.zip'))


def test_release_refuses_changed_binary_before_writing_archive(clean_source, tmp_path):
    banner = clean_source / 'assets/nextrole-banner.png'
    banner.write_bytes(banner.read_bytes() + b'PRIVATE SENTINEL')
    with pytest.raises(ValueError, match='Unreviewed binary asset refused'):
        build_release.build(clean_source, tmp_path / 'release')
    assert not list((tmp_path / 'release').glob('*.zip'))


def test_launcher_check_does_not_install_or_start_services(monkeypatch, capsys):
    monkeypatch.setattr(sys, 'argv', ['launcher.py', '--check'])
    monkeypatch.setattr(launcher, 'dependency_probe', lambda _: False)
    monkeypatch.setattr(launcher.shutil, 'which', lambda *a, **kw: None)
    def forbidden(*a, **kw):
        pytest.fail('Local check must not install or start services')
    monkeypatch.setattr(launcher, 'install_dependencies', forbidden)
    monkeypatch.setattr(launcher, 'serve', forbidden)
    launcher.main()
    assert 'not found' in capsys.readouterr().out


def test_existing_site_reopens_without_spawning_second_server(monkeypatch):
    monkeypatch.setattr(launcher, 'existing_workspace', lambda port: True)
    opened = []
    monkeypatch.setattr(launcher.webbrowser, 'open', opened.append)
    monkeypatch.setattr(launcher.subprocess, 'Popen', lambda *a, **kw: pytest.fail('Duplicate server'))
    launcher.serve(Path('/unused/python'), 8877)
    assert opened == ['http://127.0.0.1:8877/']


def test_missing_codex_still_allows_local_workspace(monkeypatch, capsys):
    monkeypatch.setattr(sys, 'argv', ['launcher.py', '--no-browser'])
    monkeypatch.setattr(launcher.shutil, 'which', lambda *a, **kw: None)
    monkeypatch.setattr(launcher, 'install_dependencies', lambda: Path('/local/python'))
    calls = []
    monkeypatch.setattr(launcher, 'serve', lambda *args: calls.append(args))
    launcher.main()
    assert calls == [(Path('/local/python'), 8877, False)]
    assert 'Local profile editing and pasted jobs still work' in capsys.readouterr().out
